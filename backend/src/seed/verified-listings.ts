/**
 * Card lineups as published on each issuer's own "all credit cards" pages, read on `fetchedOn`
 * (Claude Code session on the owner's subscription — no API billing, no aggregator data). Only what
 * the pages stated is recorded: name, personal/business, annual fee, headline earning, product page.
 * Cards whose fee a page did not state are not added. `slug` links a listing entry to a curated card
 * (real-catalog*.ts). `complete: true` means the whole lineup was read, so curated cards missing from
 * it are no longer offered to new applicants.
 *
 * Applied by applyVerifiedListings (seed/verified-listings.apply.ts) on seed / catalog:import.
 */
import type { CardNetwork, CardType } from "@prisma/client";
import { slugify } from "../domain/card-research";

export interface ListedCard {
  name: string;
  type: CardType;
  feeDollars: number;
  /** headline earning as the issuer states it */
  earning: string;
  url: string | null;
  /** curated card this entry confirms (otherwise a new card is added) */
  slug?: string;
  network?: CardNetwork;
  /** new cards: currency code (default CASH) and category earning derived from the stated rates */
  currency?: string;
  rewards?: Array<[string, number, string, number?, ("QUARTER" | "YEAR")?]>;
  features?: string[];
  /** when the page states it */
  foreignTxFee?: boolean;
}

export interface IssuerListing {
  issuer: string;
  fetchedOn: string;
  sources: string[];
  complete: boolean;
  cards: ListedCard[];
  /** curated cards the complete listing no longer shows */
  discontinued?: string[];
  /** curated cards the listing names without facts (no fee shown): only their product page is recorded */
  pagesOnly?: Array<[slug: string, url: string]>;
}

