/** Catalog slug for a listing entry: the curated slug, else issuer + name ("+" kept as "plus" so One / One+ differ). */
export function listingSlug(
  issuer: string,
  card: Pick<ListedCard, "slug" | "name">,
): string {
  if (card.slug) return card.slug;
  const name = slugify(card.name.replace(/\+/g, " plus"));
  const prefix = slugify(issuer);
  return name.startsWith(prefix) ? name : `${prefix}-${name}`;
}
